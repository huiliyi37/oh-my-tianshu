#!/usr/bin/env node
// Compile the citation vocabulary from the dsh-plugin-upgrade-skill repository.
//
//   node scripts/compile-vocabulary.mjs <path-to-dsh-plugin-upgrade-skill>
//
// Reads the curated version cards (references/v*.md) and the corridor rollup
// (rollup-*.md), and emits src/vocabulary.ts — the single source the
// cite-gate runtime checks citations against. Deterministic: re-running on the
// same upstream checkout yields byte-identical output (keys sorted).
//
// The legacy → namespaced error-code mapping is a curated copy of card
// DSH-0.1.2-A2-02 (Remote failure vocabulary); it is intentionally a code
// constant, not parsed from prose.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const repo = process.argv[2]
if (!repo) {
  console.error('usage: node scripts/compile-vocabulary.mjs <path-to-dsh-plugin-upgrade-skill>')
  process.exit(2)
}

const refsDir = join(repo, 'skills', 'plugin-upgrade', 'references')
const cardIds = []
for (const file of readdirSync(refsDir).filter(f => /^v\d.*\.md$/.test(f)).sort()) {
  const text = readFileSync(join(refsDir, file), 'utf8')
  for (const m of text.matchAll(/^###\s+(DSH-\S+)\s+·/gm)) {
    if (!cardIds.includes(m[1])) cardIds.push(m[1])
  }
}

const recipeIds = []
for (const file of readdirSync(refsDir).filter(f => /^rollup-.*\.md$/.test(f)).sort()) {
  const text = readFileSync(join(refsDir, file), 'utf8')
  for (const m of text.matchAll(/^###\s+(R-\d+)\s+·/gm)) {
    if (!recipeIds.includes(m[1])) recipeIds.push(m[1])
  }
}

// Curated from DSH-0.1.2-A2-02: the old hyphenated codes whose citation in a
// migration answer means the writer is still on the 0.1.1 vocabulary.
const legacyCodes = [
  'cancelled', 'internal', 'bad-request',
  'session-not-found', 'agent-busy',
  'agent-preset-not-found', 'agent-preset-locked',
]

// Curated from DSH-0.1.2-A2-02: the namespaced codes the alpha.2 error flow
// actually uses (existence check for the optional namespaced-code gate).
const namespacedCodes = [
  'gateway/cancelled', 'gateway/internal', 'gateway/bad-request',
  'session/not-found', 'session/agent-busy',
  'agent-preset/not-found', 'agent-preset/locked',
]

const vocabulary = {
  schemaVersion: 1,
  compiledAt: new Date().toISOString().slice(0, 10),
  cardIds,
  recipeIds,
  legacyCodes,
  namespacedCodes,
}

const out = join(import.meta.dirname, '..', 'src', 'vocabulary.ts')
// Emit a TS module instead of JSON: the monorepo builds with tsc -b, which does
// not copy JSON assets into lib/ — a generated module travels with the build.
const literal = JSON.stringify(vocabulary, null, 2)
  .replaceAll('"', "'")
  // JSON has no trailing commas; add them so the generated file satisfies
  // @stylistic/comma-dangle (last array item / last object property).
  .replaceAll(/'\n(\s*)\]/g, "',\n$1]")
  .replaceAll(/'\n(\s*)\}/g, "',\n$1}")
  .replaceAll(/]\n}/g, '],\n}')

const body = `// GENERATED by scripts/compile-vocabulary.mjs — do not edit by hand.
export interface Vocabulary {
  schemaVersion: number
  compiledAt: string
  cardIds: string[]
  recipeIds: string[]
  legacyCodes: string[]
  namespacedCodes: string[]
}

export const vocabulary: Vocabulary = ${literal}
`

writeFileSync(out, body)
console.log(`vocabulary: ${cardIds.length} cards, ${recipeIds.length} recipes → ${out}`)
